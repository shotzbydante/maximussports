/**
 * sportEvents — named events for the per-sport pages (NFL, NBA, MLB).
 *
 * The college basketball app grew its events page by page. The pro-sport
 * sections share these helpers instead, so the same action has the same event
 * name and properties in every sport and can be compared across them.
 *
 * Event taxonomy:
 *   intel_item_open     — a news story opened (same name the NCAAM feed uses)
 *   video_play_click    — a video opened (same name the NCAAM video card uses)
 *   filter_change       — a tab, filter, sort or view toggle changed on a page
 *   briefing_refresh    — the AI briefing was regenerated by the reader
 *   briefing_expand     — the AI briefing was expanded or collapsed
 *   picks_board_view    — the picks board finished loading in front of a reader
 *   team_picker_opened  — the "follow a team" picker was opened
 *   outbound_click      — a link to another site was followed
 *
 * `sport` is attached to every event automatically from the URL; it is passed
 * here too so the call sites read plainly and tests can assert it.
 */

import { track } from './index.js';

const short = (text) => (text ?? '').slice(0, 100);

/** A news story was opened. */
export function trackStoryOpen({ sport, surface, story, position }) {
  track('intel_item_open', {
    type: 'article',
    sport,
    surface,
    id: story?.link,
    title: short(story?.title),
    source: story?.source,
    topic: story?.topic,
    position,
  });
}

/** A video was opened. */
export function trackVideoOpen({ sport, surface, video, position }) {
  track('video_play_click', {
    sport,
    surface,
    video_id: video?.videoId,
    title: short(video?.title),
    channel: video?.channelTitle,
    position,
  });
}

/** A tab, filter, sort or view toggle changed. */
export function trackFilterChange({ sport, page, filter, value }) {
  track('filter_change', { sport, page, filter, value: String(value) });
}

export function trackBriefingRefresh({ sport }) {
  track('briefing_refresh', { sport });
}

export function trackBriefingExpand({ sport, expanded }) {
  track('briefing_expand', { sport, expanded });
}

/** The picks board loaded. Fired once per mount, when the data arrives. */
export function trackPicksBoardView({ sport, surface, recommended, leans }) {
  track('picks_board_view', {
    sport,
    surface,
    recommended_count: recommended,
    lean_count: leans,
    has_recommended: recommended > 0,
  });
}

/** A pick ticket's "Full breakdown" link. `rank` is its position on the board. */
export function trackPickOpen({ sport, surface, pick, rank }) {
  track('pick_card_click', {
    sport,
    surface,
    rank,
    market: pick?.market?.type,
    selection: pick?.selection?.label,
    game_id: pick?.gameId != null ? String(pick.gameId) : undefined,
  });
}

export function trackTeamPickerOpened({ sport, surface }) {
  track('team_picker_opened', { sport, surface });
}

/** A stadium flyover started playing in a game module. Once per module. */
export function trackFlyoverView({ sport, surface, venue }) {
  track('venue_flyover_view', { sport, surface, venue });
}

/** A link to another site was followed. */
export function trackOutboundClick({ sport, surface, destination }) {
  track('outbound_click', { sport, surface, destination });
}
